using System.Text;

namespace Fieldkit.Core;

/// <summary>Builds the feature parity map (docs/PARITY.md) from the catalog and module claims.</summary>
public static class ParityReport
{
    public static (int Full, int Partial, int Native, int Planned) Counts()
    {
        int full = 0, partial = 0, native = 0, planned = 0;
        foreach (var f in FeatureCatalog.Upstream)
        {
            switch (Status(f.Id))
            {
                case Parity.Full: full++; break;
                case Parity.Partial: partial++; break;
                case Parity.Native: native++; break;
                default: planned++; break;
            }
        }
        return (full, partial, native, planned);
    }

    public static Parity Status(string featureId) =>
        FeatureRuntime.Registry.Parity.TryGetValue(featureId, out var claim) ? claim.Parity : Parity.Planned;

    public static string Markdown()
    {
        var (full, partial, native, planned) = Counts();
        var sb = new StringBuilder();
        sb.AppendLine("# Feature parity with Vorssaint (macOS)");
        sb.AppendLine();
        sb.AppendLine($"Generated by `{AppInfo.Name}.exe --write-parity` from `Core/FeatureCatalog.cs` and the claims each module makes.");
        sb.AppendLine("Feature ids are the upstream `AppFeature` raw values.");
        sb.AppendLine();
        sb.AppendLine($"**{FeatureCatalog.Upstream.Count} features:** {full} full · {partial} partial · {native} built into Windows · {planned} not built yet");
        sb.AppendLine();
        sb.AppendLine("Legend: ✅ full · 🟡 partial · 🪟 built into Windows · ⏳ not built yet");
        foreach (var group in FeatureCatalog.Upstream.GroupBy(f => f.Group))
        {
            sb.AppendLine();
            sb.AppendLine($"## {FeatureCatalog.GroupTitle(group.Key)}");
            sb.AppendLine();
            sb.AppendLine("| | Feature | Upstream id | Windows approach | Notes |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var f in group)
            {
                var claim = FeatureRuntime.Registry.Parity.GetValueOrDefault(f.Id);
                var mark = Status(f.Id) switch
                {
                    Parity.Full => "✅",
                    Parity.Partial => "🟡",
                    Parity.Native => "🪟",
                    _ => "⏳",
                };
                sb.AppendLine($"| {mark} | {Escape(f.Title)} | `{f.Id}` | {Escape(f.WindowsApproach)} | {Escape(claim?.Note ?? string.Empty)} |");
            }
        }
        var extras = FeatureCatalog.All.Where(f => f.Extra).ToList();
        if (extras.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Fieldkit extras");
            sb.AppendLine();
            sb.AppendLine("Features Fieldkit adds beyond Vorssaint's set (not counted above).");
            sb.AppendLine();
            sb.AppendLine("| Feature | Id | What it does |");
            sb.AppendLine("|---|---|---|");
            foreach (var f in extras) sb.AppendLine($"| {Escape(f.Title)} | `{f.Id}` | {Escape(f.WindowsApproach)} |");
        }
        return sb.ToString();
    }

    private static string Escape(string s) => s.Replace("|", "\\|").ReplaceLineEndings(" ");
}
